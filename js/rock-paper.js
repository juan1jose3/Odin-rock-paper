let gameCount = 0;
let humanScore = 0;
let botScore = 0;
const maxRounds = 5;






function computerChoice(){
    const randomChoice = Math.floor(Math.random() * 3) + 1;
    let choice;
    if(randomChoice === 1){
        choice = "rockBot";
    }else if(randomChoice === 2){
        choice = "paperBot";
    }else{
        choice = "scissorsBot";
    }

    return choice;
}

function setScore(){
    let humanPoints = document.querySelector(".humanPoints");
    let botPoints = document.querySelector(".botPoints");

    humanPoints.textContent = humanScore;

    botPoints.textContent = botScore;

}

function humanChoice(){
    let choice = document.querySelector(".choice");
    let items = document.querySelector(".items");
    let info = document.querySelector(".info");


    

    choice.addEventListener("click",(event)=>{
        let btn = event.target.closest("button");

        if (!btn) return;

        if(gameCount <= 5){
            
          let human = btn.id;
        
          switch(human){
              case "rock":
                  
                  items.textContent = asciiAssets.rockConsole;
                  break;
              
              case "paper":
                  items.textContent = asciiAssets.paperConsole;
                  break;
              
              case "scissors":
                  items.textContent = asciiAssets.scissorConsole;
                  break;
              
          }
          playRound(human);
            
        }else{
            info.textContent = "Game Over";
            let buttonContainer = document.createElement("div")
            let playAgain = document.createElement("button");
            let log = document.querySelector(".log");
            
           

            playAgain.textContent = "play Again";
            playAgain.classList.add("terminalButton");
            playAgain.classList.add("bracket");
           

            buttonContainer.appendChild(playAgain);
            info.appendChild(buttonContainer);
            
            setTimeout(() =>{
              let state = showState();
               log.textContent = state;
               if(humanScore > botScore){
                  log.classList.add("error");
               }else{
                log.classList.add("success");
               }
              
               
               info.appendChild(log);
            },500);

            playAgain.addEventListener("click",() =>{
                location.reload(); // refreshes the page
                
            });
        }
       
        
    });

    
}


function playRound(human){
    let info = document.querySelector(".info");
    let robot = computerChoice();
    if((human == "rock" && robot == "scissorsBot") || (human == "paper" && robot == "rockBot") || (human == "scissors" && robot == "paperBot")){
        info.textContent = "Human wins";
        humanScore ++;
        setScore();
        
    }else if(human == robot.replace("Bot","")){
        info.textContent = "Draw!";
    }else{
        info.textContent = "Robot wins"
        botScore ++;
        setScore();
    }

    gameCount ++;

    showSelection(human,robot);
    

}

function showSelection(human,robot){
    
    
    let humanAnimation = document.querySelector(".humanAnimation");
    let botAnimation = document.querySelector(".botAnimation");

    let humanSection = document.querySelector(".humanSection");
    let botSection = document.querySelector(".botSection");

    
    humanSection.textContent = asciiAssets[human];

    botSection.textContent = asciiAssets[robot];
            
   
    humanAnimation.classList.remove("box");
    botAnimation.classList.remove("box");

    void humanAnimation.offsetWidth; 
    void botAnimation.offsetWidth;

    humanAnimation.classList.add("box");
    botAnimation.classList.add("box");

}

function showState(){


  logs = {
    botDefeatedLogs:[
      "[ ERR ] ai.core: outcome unpredicted",
      "[ WARN ] ai.core: confidence threshold breached",
      "[ INFO ] ai.core: learning update queued",
      "[ ERR ] ai.core: decision path invalid",
      "[ WARN ] ai.core: unexpected human strategy"

    ],

    botWinLogs:[
      "[ OK ] ai.core: outcome predicted",
      "[ INFO ] ai.core: strategy executed successfully",
      "[ INFO ] ai.core: optimal response selected",
      "[ INFO ] ai.core: efficiency within expected bounds",
      "[ INFO ] ai.core: confidence increased"
    ]
  };
  

  let randomLog; 
  if(humanScore > botScore){
    let defeatLogs = logs.botDefeatedLogs;
    randomLog = Math.floor(Math.random() * defeatLogs.length);
    return  "Bot logs: " + ` [${getTimeStamp()}] `+ defeatLogs[randomLog];

  }

  let winLogs = logs.botWinLogs;
  randomLog = Math.floor(Math.random() * winLogs.length);
  return "Bot logs: " + `[${getTimeStamp()}] `+ winLogs[randomLog];
  



};

function getTimeStamp(){
  const now = new Date();
  const mm = String(now.getMinutes()).padStart(2,"0");
  const s = String(now.getSeconds()).padStart(2,"0");
  return `${mm} : ${s}`;
}

