function playRound(human){
    let robot = computerChoice();
    if((human == "rock" && robot == "scissors") || (human == "paper" && robot == "rock") || (human == "scissors" && robot == "paper")){
        console.log("human wins");
        humanScore ++;
        setScore();
    }else if(human == robot){
        console.log("draw")
    }else{
        console.log("robot wins");
        botScore ++;
        setScore();
    }

    gameCount ++;

}



